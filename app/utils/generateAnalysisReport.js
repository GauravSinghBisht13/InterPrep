function addTwoColumnLists(
  doc,
  leftTitle,
  leftItems,
  rightTitle,
  rightItems,
  y,
) {
  const gap = 6;

  const width = (PAGE.width - PAGE.margin * 2 - gap) / 2;

  const leftHeight = 18 + (leftItems?.length || 0) * 11;

  const rightHeight = 18 + (rightItems?.length || 0) * 11;

  const height = Math.max(leftHeight, rightHeight, 30);

  y = ensureSpace(doc, y, height);

  drawRoundedCard(doc, PAGE.margin, y, width, height, {
    fill: COLORS.white,
    border: COLORS.border,
  });

  drawRoundedCard(doc, PAGE.margin + width + gap, y, width, height, {
    fill: COLORS.white,
    border: COLORS.border,
  });

  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);

  setTextColor(doc, COLORS.success);

  doc.text(leftTitle, PAGE.margin + 7, y + 9);

  setTextColor(doc, COLORS.danger);

  doc.text(rightTitle, PAGE.margin + width + gap + 7, y + 9);

  const drawItems = (items, x, color) => {
    if (!items?.length) {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(7.5);
      setTextColor(doc, COLORS.muted);

      doc.text("None identified", x, y + 18);

      return;
    }

    items.forEach((item, index) => {
      const text =
        typeof item === "string" ? item : item?.text || item?.name || "";

      doc.setFont("helvetica", "bold");
      doc.setFontSize(8);

      setTextColor(doc, color);

      doc.text("•", x, y + 18 + index * 11);

      doc.setFont("helvetica", "normal");

      setTextColor(doc, COLORS.text);

      const lines = splitText(doc, text, width - 16);

      doc.text(lines[0] || "", x + 5, y + 18 + index * 11);
    });
  };

  drawItems(leftItems, PAGE.margin + 7, COLORS.success);

  drawItems(rightItems, PAGE.margin + width + gap + 7, COLORS.danger);

  return y + height + 7;
}

function addRecommendations(doc, recommendations, y) {
  if (!recommendations?.length) {
    return y;
  }

  y = addSectionTitle(
    doc,
    "AI Improvement Plan",
    y,
    "Practical actions to improve the resume-job match",
  );

  recommendations.forEach((recommendation, index) => {
    const text =
      typeof recommendation === "string"
        ? recommendation
        : recommendation?.text || recommendation?.recommendation || "";

    if (!text) {
      return;
    }

    const lines = splitText(doc, text, PAGE.width - PAGE.margin * 2 - 18);

    const height = Math.max(15, lines.length * 8 * 0.3528 * 1.35 + 10);

    y = ensureSpace(doc, y, height + 3);

    drawRoundedCard(doc, PAGE.margin, y, PAGE.width - PAGE.margin * 2, height, {
      fill: COLORS.white,
      border: COLORS.border,
    });

    setFillColor(doc, COLORS.primary);

    doc.circle(PAGE.margin + 8, y + 8, 4, "F");

    doc.setFont("helvetica", "bold");
    doc.setFontSize(7);

    setTextColor(doc, COLORS.white);

    doc.text(String(index + 1), PAGE.margin + 8, y + 10.2, {
      align: "center",
    });

    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);

    setTextColor(doc, COLORS.text);

    doc.text(lines, PAGE.margin + 16, y + 8);

    y += height + 3;
  });

  return y + 2;
}

