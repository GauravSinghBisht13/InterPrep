function addResponsibilitiesSection(doc, responsibilities, y) {
  y = addSectionTitle(
    doc,
    "Responsibility Alignment",
    y,
    "Comparison of job responsibilities with resume evidence",
  );

  const total = responsibilities?.total || 0;

  const matched = responsibilities?.matched || 0;

  const partial = responsibilities?.partially_matched || 0;

  const missing = responsibilities?.missing || 0;

  const score = total > 0 ? ((matched + partial * 0.5) / total) * 100 : 0;

  y = ensureSpace(doc, y, 24);

  const boxWidth = (PAGE.width - PAGE.margin * 2 - 9) / 4;

  const items = [
    ["Total", total, COLORS.info],
    ["Matched", matched, COLORS.success],
    ["Partial", partial, COLORS.warning],
    ["Missing", missing, COLORS.danger],
  ];

  items.forEach(([label, value, color], index) => {
    addInfoCard(
      doc,
      label,
      String(value),
      PAGE.margin + index * (boxWidth + 3),
      y,
      boxWidth,
      {
        color,
      },
    );
  });

  y += 34;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);

  setTextColor(doc, COLORS.text);

  doc.text(`Responsibility Match: ${Math.round(score)}%`, PAGE.margin, y);

  addProgressBar(doc, PAGE.margin + 55, y - 3, 105, score, COLORS.primary);

  y += 10;

  const details = responsibilities?.details || [];

  details.forEach((item) => {
    const responsibility = item?.responsibility || "Responsibility";

    const status = item?.status || "unknown";

    const evidence = item?.evidence || "";

    const statusColor =
      status === "matched"
        ? COLORS.success
        : status === "partially_matched"
          ? COLORS.warning
          : COLORS.danger;

    const statusLabel =
      status === "matched"
        ? "MATCHED"
        : status === "partially_matched"
          ? "PARTIAL"
          : "MISSING";

    const evidenceLines = evidence ? splitText(doc, evidence, 142) : [];

    const height = 16 + evidenceLines.length * 7.5 * 0.3528 * 1.35;

    y = ensureSpace(doc, y, height + 3);

    drawRoundedCard(doc, PAGE.margin, y, PAGE.width - PAGE.margin * 2, height, {
      fill: COLORS.white,
      border: COLORS.border,
    });

    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);

    setTextColor(doc, COLORS.text);

    const responsibilityLines = splitText(doc, responsibility, 105);

    doc.text(responsibilityLines, PAGE.margin + 7, y + 7);

    doc.setFont("helvetica", "bold");
    doc.setFontSize(6.5);

    setTextColor(doc, statusColor);

    doc.text(statusLabel, PAGE.width - PAGE.margin - 7, y + 7, {
      align: "right",
    });

    if (evidence) {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(7.2);

      setTextColor(doc, COLORS.muted);

      doc.text(
        evidenceLines,
        PAGE.margin + 7,
        y + 7 + responsibilityLines.length * 3.8 + 4,
      );
    }

    y += height + 3;
  });

  return y + 2;
}

