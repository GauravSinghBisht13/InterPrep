/**
 * Generates a professional structured PDF report.
 *
 * @param {Object} analysisData - Analysis response or analysis.data object
 * @param {Object} options
 * @param {string} options.resumeName - Optional uploaded resume filename
 */
export async function generateAnalysisReport(analysisData, options = {}) {
  if (!analysisData) {
    throw new Error("Analysis data is required to generate the report.");
  }

  const data = analysisData?.data || analysisData;

  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
    compress: true,
  });

  const resumeName = options?.resumeName || "";

  // --------------------------------------------------
  // COVER PAGE
  // --------------------------------------------------

  addReportCover(doc, data, resumeName);

  // --------------------------------------------------
  // PAGE 2
  // --------------------------------------------------

  doc.addPage();

  let y = 31;

  y = addSectionTitle(
    doc,
    "Analysis Overview",
    y,
    "A detailed breakdown of resume compatibility",
  );

  y = addScoreOverview(doc, data?.ats, y);

  y = addScoreBreakdown(doc, data?.ats?.breakdown, y);

  // --------------------------------------------------
  // SKILLS
  // --------------------------------------------------

  y = addSectionTitle(
    doc,
    "Skills Analysis",
    y,
    "Skills identified from the resume and job description",
  );

  y = addSkillSection(doc, "Matched Skills", data?.matched_skills, y, {
    color: COLORS.success,
    background: COLORS.successBg,
    icon: "✓",
  });

  y = addSkillSection(
    doc,
    "Partially Matched",
    data?.partially_matched_skills,
    y,
    {
      color: COLORS.warning,
      background: COLORS.warningBg,
      icon: "◐",
    },
  );

  y = addSkillSection(doc, "Missing Skills", data?.missing_skills, y, {
    color: COLORS.danger,
    background: COLORS.dangerBg,
    icon: "✕",
  });

  // --------------------------------------------------
  // EXPERIENCE
  // --------------------------------------------------

  y = addExperienceSection(doc, data?.experience, y);

  // --------------------------------------------------
  // EDUCATION
  // --------------------------------------------------

  y = addEducationSection(doc, data?.education, y);

  // --------------------------------------------------
  // RESPONSIBILITIES
  // --------------------------------------------------

  y = addResponsibilitiesSection(doc, data?.responsibilities, y);

  // --------------------------------------------------
  // ALIGNMENT SUMMARY
  // --------------------------------------------------

  y = addParagraph(
    doc,
    "Experience Alignment Summary",
    data?.experience_alignment,
    y,
  );

  y = addParagraph(
    doc,
    "Responsibility Alignment Summary",
    data?.responsibility_alignment,
    y,
  );

  // --------------------------------------------------
  // STRENGTHS / WEAKNESSES
  // --------------------------------------------------

  y = ensureSpace(doc, y, 60);

  y = addSectionTitle(
    doc,
    "Candidate Assessment",
    y,
    "Key strengths and potential gaps identified by the analysis",
  );

  y = addTwoColumnLists(
    doc,
    "Strengths",
    data?.strengths || [],
    "Weaknesses",
    data?.weaknesses || [],
    y,
  );

  // --------------------------------------------------
  // RESUME QUALITY
  // --------------------------------------------------

  y = addResumeQualitySection(doc, data?.resume_quality, y);

  // --------------------------------------------------
  // RECOMMENDATIONS
  // --------------------------------------------------

  y = addRecommendations(doc, data?.recommendations, y);

  // --------------------------------------------------
  // PAGE NUMBERS + FOOTERS
  // --------------------------------------------------

  const totalPages = doc.getNumberOfPages();

  for (let page = 1; page <= totalPages; page++) {
    doc.setPage(page);

    if (page > 1) {
      drawPageHeader(doc, page, totalPages);
    }

    drawFooter(doc);
  }

  // --------------------------------------------------
  // DOWNLOAD
  // --------------------------------------------------

  const date = new Date().toISOString().split("T")[0];

  const filename = `InterPrep-Resume-Analysis-${date}.pdf`;

  doc.save(filename);

  return filename;
}

export default generateAnalysisReport;
