function safeText(value, fallback = "") {
  if (value === null || value === undefined) {
    return fallback;
  }

  return String(value);
}

function clamp(value, min = 0, max = 100) {
  const number = Number(value);

  if (Number.isNaN(number)) {
    return min;
  }

  return Math.min(Math.max(number, min), max);
}

function getSkillName(skill) {
  if (typeof skill === "string") {
    return skill;
  }

  return skill?.skill || skill?.name || "Unknown skill";
}

function getSkillEvidence(skill) {
  if (typeof skill === "object") {
    return skill?.evidence || "";
  }

  return "";
}

function setTextColor(doc, color) {
  doc.setTextColor(...color);
}

function setFillColor(doc, color) {
  doc.setFillColor(...color);
}

function setDrawColor(doc, color) {
  doc.setDrawColor(...color);
}

function drawRoundedCard(doc, x, y, width, height, options = {}) {
  const { fill = COLORS.white, border = COLORS.border, radius = 4 } = options;

  setFillColor(doc, fill);
  setDrawColor(doc, border);

  doc.setLineWidth(0.25);
  doc.roundedRect(x, y, width, height, radius, radius, "FD");
}

function splitText(doc, text, width) {
  return doc.splitTextToSize(safeText(text), width);
}

function getTextHeight(doc, text, width, fontSize = 9, lineHeight = 1.35) {
  doc.setFontSize(fontSize);

  const lines = splitText(doc, text, width);

  return lines.length * fontSize * 0.3528 * lineHeight;
}

