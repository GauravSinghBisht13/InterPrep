function addParagraph(doc, title, text, y) {
  if (!text) {
    return y;
  }

  const width = PAGE.width - PAGE.margin * 2;

  const lines = splitText(doc, text, width);

  const height = lines.length * 8.5 * 0.3528 * 1.4 + 14;

  y = ensureSpace(doc, y, height);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(8.5);
  setTextColor(doc, COLORS.text);

  doc.text(title, PAGE.margin, y);

  y += 5;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  setTextColor(doc, COLORS.muted);

  doc.text(lines, PAGE.margin, y);

  return y + lines.length * 8.5 * 0.3528 * 1.4 + 5;
}

function addScoreOverview(doc, ats, y) {
  const score = clamp(ats?.atsScore || 0);

  const cardWidth = PAGE.width - PAGE.margin * 2;

  const cardHeight = 57;

  y = ensureSpace(doc, y, cardHeight);

  drawRoundedCard(doc, PAGE.margin, y, cardWidth, cardHeight, {
    fill: COLORS.white,
    border: COLORS.border,
    radius: 5,
  });

  // Accent background
  setFillColor(doc, [245, 243, 255]);

  doc.roundedRect(PAGE.margin, y, 53, cardHeight, 5, 5, "F");

  // Score circle
  const centerX = PAGE.margin + 26.5;

  const centerY = y + 28;

  setDrawColor(doc, [221, 214, 254]);

  doc.setLineWidth(5);

  doc.circle(centerX, centerY, 16, "S");

  setDrawColor(doc, COLORS.primary);

  doc.setLineWidth(5);

  // Approximate progress using segmented arc
  const segments = 36;
  const activeSegments = Math.round((score / 100) * segments);

  for (let i = 0; i < activeSegments; i++) {
    const angle = -Math.PI / 2 + (i / segments) * Math.PI * 2;

    const nextAngle = -Math.PI / 2 + ((i + 0.72) / segments) * Math.PI * 2;

    const r = 16;

    const x1 = centerX + Math.cos(angle) * r;

    const y1 = centerY + Math.sin(angle) * r;

    const x2 = centerX + Math.cos(nextAngle) * r;

    const y2 = centerY + Math.sin(nextAngle) * r;

    doc.line(x1, y1, x2, y2);
  }

  doc.setFont("helvetica", "bold");

  doc.setFontSize(17);

  setTextColor(doc, COLORS.primaryDark);

  doc.text(`${Math.round(score)}%`, centerX, centerY + 2, {
    align: "center",
  });

  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);

  setTextColor(doc, COLORS.text);

  doc.text("ATS Match Score", PAGE.margin + 62, y + 14);

  let scoreLabel = "Needs Improvement";

  if (score >= 80) {
    scoreLabel = "Strong Match";
  } else if (score >= 65) {
    scoreLabel = "Good Match";
  } else if (score >= 50) {
    scoreLabel = "Moderate Match";
  }

  doc.setFont("helvetica", "bold");

  doc.setFontSize(8);

  setTextColor(
    doc,
    score >= 70 ? COLORS.success : score >= 50 ? COLORS.warning : COLORS.danger,
  );

  doc.text(scoreLabel, PAGE.margin + 62, y + 21);

  doc.setFont("helvetica", "normal");

  doc.setFontSize(7.5);

  setTextColor(doc, COLORS.muted);

  const description =
    "Estimated compatibility between the candidate resume and the provided job description.";

  const descriptionLines = splitText(doc, description, cardWidth - 72);

  doc.text(descriptionLines, PAGE.margin + 62, y + 28);

  return y + cardHeight + 7;
}

